#!/usr/bin/env python3
# #### JO added (2026-10-27, systolic Phase D): writes gemm_sa_bd.v, the block-design wrapper of gemm_sa (one BRAM
# interface per wgt bank cannot be a Verilog array, hence a generator).  usage: python3 gen_gemm_sa_bd.py > gemm_sa_bd.v
N = 16
def bram(name, mode, aw_bytes_log, width, lat=None):
    nb = width // 8
    io_m = mode == 'Master'
    o, i = ('output', 'input') if io_m else ('input', 'output')
    par = f'MODE {mode}, MASTER_TYPE BRAM_CTRL, MEM_WIDTH {width}' + (f', READ_LATENCY {lat}' if lat else '')
    return [
        f'  (* X_INTERFACE_INFO = "xilinx.com:interface:bram:1.0 {name} ADDR" *) (* X_INTERFACE_PARAMETER = "{par}" *)',
        f'  {o:6s} wire [31:0]        {name}_addr,',
        f'  (* X_INTERFACE_INFO = "xilinx.com:interface:bram:1.0 {name} CLK" *)  {o:6s} wire {name}_clk,',
        f'  (* X_INTERFACE_INFO = "xilinx.com:interface:bram:1.0 {name} DIN" *)  {o:6s} wire [{width-1}:0] {name}_din,',
        f'  (* X_INTERFACE_INFO = "xilinx.com:interface:bram:1.0 {name} DOUT" *) {i:6s} wire [{width-1}:0] {name}_dout,',
        f'  (* X_INTERFACE_INFO = "xilinx.com:interface:bram:1.0 {name} EN" *)   {o:6s} wire {name}_en,',
        f'  (* X_INTERFACE_INFO = "xilinx.com:interface:bram:1.0 {name} WE" *)   {o:6s} wire [{nb-1}:0] {name}_we,',
        f'  (* X_INTERFACE_INFO = "xilinx.com:interface:bram:1.0 {name} RST" *)  {o:6s} wire {name}_rst,',
    ]
L = []
L.append('''// #### JO added (2026-10-27, systolic Phase D, docs/evta_systolic_design.md §2): block-design wrapper of gemm_sa.
// GENERATED by gen_gemm_sa_bd.py, do not edit.
// - hls_acc_a/b, hls_out: the BRAM ports of the HLS compute (acc_mem_V_PORTA/B, out_mem_V_PORTA) come in here;
//   mem_acc_a/b, mem_out go to acc_mem PORTA/B and out_mem PORTA. busy = 1: gemm_sa drives them (acc read on A,
//   acc write on B), else the HLS ports pass through. compute never touches acc/out while gemm_sa has work.
// - mem_inp, mem_wgt0..15: port B of inp_mem and of the 16 wgt banks (read only, latency L_RD).
// BRAM addresses are byte addresses (Stand_Alone blk_mem_gen with 32-bit addresses), write enables per byte.
`timescale 1ns / 1ps
module gemm_sa_bd #(
  parameter DW = 12, SW = 12, WW = 11,
  parameter L_RD = 2,
  parameter UB = 40                      // uop TDATA width of the HLS stream (bytes)
) (
  (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF s_uop:m_done:s_g2l:m_g2l:s_g2s:m_g2s:hls_acc_a:hls_acc_b:hls_out:mem_acc_a:mem_acc_b:mem_out:mem_inp''' +
  ''.join(f':mem_wgt{j}' for j in range(N)) + ''', ASSOCIATED_RESET rstn" *)
  input  wire                 clk,
  input  wire                 rstn,
  input  wire [UB-1:0]        s_uop_tdata,
  input  wire                 s_uop_tvalid,
  output wire                 s_uop_tready,
  output wire [7:0]           m_done_tdata,
  output wire                 m_done_tvalid,
  input  wire                 m_done_tready,
  // g2l / g2s dependence queues: compute's pushes (s_*) and gemm_sa's (finished GEMM instructions) merged into m_*;
  // gemm_sa first (compute only pushes when gemm_sa has nothing outstanding, so the order is kept)
  input  wire [7:0]           s_g2l_tdata,
  input  wire                 s_g2l_tvalid,
  output wire                 s_g2l_tready,
  output wire [7:0]           m_g2l_tdata,
  output wire                 m_g2l_tvalid,
  input  wire                 m_g2l_tready,
  input  wire [7:0]           s_g2s_tdata,
  input  wire                 s_g2s_tvalid,
  output wire                 s_g2s_tready,
  output wire [7:0]           m_g2s_tdata,
  output wire                 m_g2s_tvalid,
  input  wire                 m_g2s_tready,''')
L += bram('hls_acc_a', 'Slave', 0, 512) + bram('hls_acc_b', 'Slave', 0, 512) + bram('hls_out', 'Slave', 0, 128)
L += bram('mem_acc_a', 'Master', 0, 512, 2) + bram('mem_acc_b', 'Master', 0, 512, 2) + bram('mem_out', 'Master', 0, 128, 1)
L += bram('mem_inp', 'Master', 0, 128, 2)          # read latency = L_RD (2: port B output register on)
for j in range(N): L += bram(f'mem_wgt{j}', 'Master', 0, 128, 2)
L.append('  output wire                 busy\n);')
body = '''
  localparam N = 16;
  wire                inp_en;
  wire [SW-1:0]       inp_addr;
  wire [N-1:0]        wgt_en;
  wire [WW*N-1:0]     wgt_addr;
  wire                acc_rd_en, acc_wr_en, out_wr_en;
  wire [DW-1:0]       acc_rd_addr, acc_wr_addr, out_wr_addr;
  wire [32*N-1:0]     acc_wr_data;
  wire [8*N-1:0]      out_wr_data;
  wire [128*N-1:0]    wgt_data;
  wire                sa_g2l_v, sa_g2l_r, sa_g2s_v, sa_g2s_r;
  assign m_g2l_tvalid = sa_g2l_v || s_g2l_tvalid;
  assign m_g2l_tdata  = 8'd1;
  assign sa_g2l_r     = m_g2l_tready;
  assign s_g2l_tready = m_g2l_tready && !sa_g2l_v;
  assign m_g2s_tvalid = sa_g2s_v || s_g2s_tvalid;
  assign m_g2s_tdata  = 8'd1;
  assign sa_g2s_r     = m_g2s_tready;
  assign s_g2s_tready = m_g2s_tready && !sa_g2s_v;

  gemm_sa #(.N(N), .DW(DW), .SW(SW), .WW(WW), .L_RD(L_RD)) sa (
    .clk(clk), .rstn(rstn),
    .s_uop_tdata(s_uop_tdata[DW+SW+WW+4:0]), .s_uop_tvalid(s_uop_tvalid), .s_uop_tready(s_uop_tready),
    .m_done_tdata(m_done_tdata), .m_done_tvalid(m_done_tvalid), .m_done_tready(m_done_tready),
    .m_g2l_tvalid(sa_g2l_v), .m_g2l_tready(sa_g2l_r), .m_g2s_tvalid(sa_g2s_v), .m_g2s_tready(sa_g2s_r),
    .inp_en(inp_en), .inp_addr(inp_addr), .inp_data(mem_inp_dout),
    .wgt_en(wgt_en), .wgt_addr(wgt_addr), .wgt_data(wgt_data),
    .acc_rd_en(acc_rd_en), .acc_rd_addr(acc_rd_addr), .acc_rd_data(mem_acc_a_dout),
    .acc_wr_en(acc_wr_en), .acc_wr_addr(acc_wr_addr), .acc_wr_data(acc_wr_data),
    .out_wr_en(out_wr_en), .out_wr_addr(out_wr_addr), .out_wr_data(out_wr_data),
    .busy(busy));

  // acc / out: gemm_sa while busy, else the HLS compute
  assign mem_acc_a_clk  = clk;
  assign mem_acc_a_rst  = 1'b0;
  assign mem_acc_a_addr = busy ? {{(26-DW){1'b0}}, acc_rd_addr, 6'd0} : hls_acc_a_addr;
  // #### JO changed (Phase D, board): read enables stay high. With the primitive output register on and no REGCE pin,
  // #### blk_mem_gen updates the output register only while EN is 1, so a one-cycle EN pulse never reaches dout
  // #### (first board run: every product 0). Was: busy ? acc_rd_en : hls_acc_a_en
  assign mem_acc_a_en   = busy ? 1'b1 : hls_acc_a_en;
  assign mem_acc_a_we   = busy ? 64'd0 : hls_acc_a_we;
  assign mem_acc_a_din  = hls_acc_a_din;
  assign hls_acc_a_dout = mem_acc_a_dout;
  assign mem_acc_b_clk  = clk;
  assign mem_acc_b_rst  = 1'b0;
  assign mem_acc_b_addr = busy ? {{(26-DW){1'b0}}, acc_wr_addr, 6'd0} : hls_acc_b_addr;
  assign mem_acc_b_en   = busy ? acc_wr_en : hls_acc_b_en;
  assign mem_acc_b_we   = busy ? {64{acc_wr_en}} : hls_acc_b_we;
  assign mem_acc_b_din  = busy ? acc_wr_data : hls_acc_b_din;
  assign hls_acc_b_dout = mem_acc_b_dout;
  assign mem_out_clk    = clk;
  assign mem_out_rst    = 1'b0;
  assign mem_out_addr   = busy ? {{(28-DW){1'b0}}, out_wr_addr, 4'd0} : hls_out_addr;
  assign mem_out_en     = busy ? out_wr_en : hls_out_en;
  assign mem_out_we     = busy ? {16{out_wr_en}} : hls_out_we;
  assign mem_out_din    = busy ? out_wr_data : hls_out_din;
  assign hls_out_dout   = mem_out_dout;

  // inp / wgt port B: read only
  assign mem_inp_clk  = clk;
  assign mem_inp_rst  = 1'b0;
  assign mem_inp_addr = {{(28-SW){1'b0}}, inp_addr, 4'd0};
  assign mem_inp_en   = 1'b1;   // read only, see mem_acc_a_en (was inp_en)
  assign mem_inp_we   = 16'd0;
  assign mem_inp_din  = 128'd0;
'''
for j in range(N):
    body += f'''  assign mem_wgt{j}_clk  = clk;
  assign mem_wgt{j}_rst  = 1'b0;
  assign mem_wgt{j}_addr = {{{{(28-WW){{1'b0}}}}, wgt_addr[WW*{j} +: WW], 4'd0}};
  assign mem_wgt{j}_en   = 1'b1;   // read only, see mem_acc_a_en (was wgt_en[{j}])
  assign mem_wgt{j}_we   = 16'd0;
  assign mem_wgt{j}_din  = 128'd0;
  assign wgt_data[128*{j} +: 128] = mem_wgt{j}_dout;
'''
body += 'endmodule\n'
print('\n'.join(L) + body)
